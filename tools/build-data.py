"""Convert the captured MonkeyType data (captured/) into script-loadable files (web/data/).

Script tags work from file:// and from the WebView2 host alike, unlike fetch().
Run:  python tools/build-data.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CAP = os.path.join(ROOT, "captured")
OUT = os.path.join(ROOT, "web", "data")
os.makedirs(OUT, exist_ok=True)


def write_js(name, var, obj):
    path = os.path.join(OUT, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write("// generated by tools/build-data.py from captured/ - do not edit\n")
        f.write(f"window.{var} = ")
        json.dump(obj, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    print(f"{name:28s} {os.path.getsize(path):>9,d} bytes")


# languages -> one file, keyed by name (all English sets are small)
langs = {}
for fn in sorted(os.listdir(os.path.join(CAP, "languages"))):
    d = json.load(open(os.path.join(CAP, "languages", fn), encoding="utf-8"))
    langs[d["name"]] = {"name": d["name"], "words": d["words"],
                        "orderedByFrequency": d.get("orderedByFrequency", False)}
write_js("languages.js", "MT_LANGUAGES", langs)

# quotes -> keep only the fields the app uses
q = json.load(open(os.path.join(CAP, "quotes", "english.json"), encoding="utf-8"))
quotes = {"groups": q["groups"],
          "quotes": [[x["id"], x["text"], x["source"]] for x in q["quotes"]]}
write_js("quotes-english.js", "MT_QUOTES", quotes)

# themes -> [bg, main, caret, sub, subAlt, text, error, errorExtra, colorfulError, colorfulErrorExtra]
t = json.load(open(os.path.join(CAP, "themes.json"), encoding="utf-8"))
keys = ["bg", "main", "caret", "sub", "subAlt", "text", "error", "errorExtra",
        "colorfulError", "colorfulErrorExtra"]
themes = {name: [v.get(k, v.get("error")) for k in keys] for name, v in sorted(t.items())}
write_js("themes.js", "MT_THEMES", themes)
